"""Sync runtime prompts to PROMPTS.md and README.md; --check detects drift."""
from pathlib import Path
import argparse
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from agents.experts import DOIExpert, AccessionExpert, MetadataExpert
from agents.emit_debate import (Prosecutor, Defender, EmitJudge,
    CONVENTIONAL_PROSECUTOR, CONVENTIONAL_DEFENDER, CONVENTIONAL_JUDGE)
from agents.bare_llm import SYSTEM as BARE
from agents.single_agent import SingleAgent

README_BEGIN = "<!-- BEGIN GENERATED AGENT PROMPTS -->"
README_END = "<!-- END GENERATED AGENT PROMPTS -->"
CORE_ROLES = (
    (DOIExpert, "Discovery", "Dataset DOI references", "agents/experts.py"),
    (AccessionExpert, "Discovery", "Database accession references", "agents/experts.py"),
    (MetadataExpert, "Discovery", "Registered article-dataset links", "agents/experts.py"),
    (Prosecutor, "Validation", "Examine disqualifying red flags", "agents/emit_debate.py"),
    (Defender, "Validation", "Respond to the prosecution", "agents/emit_debate.py"),
    (EmitJudge, "Validation", "Arbitrate while protecting recall", "agents/emit_debate.py"),
)


def prompt_block(prompt: str) -> str:
    fence = chr(96) * 3
    return f"{fence}text\n{prompt.strip()}\n{fence}\n"


def render() -> str:
    roles = [(c.name, c.system) for c, _, _, _ in CORE_ROLES]
    roles.append((SingleAgent.name, SingleAgent.system))
    roles += [("BareLLM", BARE), ("Conventional Prosecutor", CONVENTIONAL_PROSECUTOR),
              ("Conventional Defender", CONVENTIONAL_DEFENDER), ("Conventional Judge", CONVENTIONAL_JUDGE)]
    sections = ["# Runtime role prompts\n\nGenerated from the Python classes. Do not edit this file manually.\n"]
    for name, prompt in roles:
        sections.append(f"## {name}\n\n{prompt_block(prompt)}")
    return "\n".join(sections)


def render_readme_prompts() -> str:
    sections = [
        "## Agent prompts\n",
        "The six core AAMAD roles are shown in full below. Each block is the exact\n"
        "runtime `system` message, including shared instructions, exported from the\n"
        "linked Python class. These blocks are not abbreviated examples.\n",
        "| Stage | Agent | Task | Runtime source |\n"
        "| --- | --- | --- | --- |",
    ]
    for role, stage, task, source in CORE_ROLES:
        sections.append(f"| {stage} | [{role.name}](#{role.name.lower()}) | {task} | [{source}]({source}) |")
    sections += [
        "",
        "Per-request `user` messages contain the article and candidate evidence.\n"
        "Discovery calls receive candidate batches. The Defender also receives the\n"
        "complete prosecution, and the Judge receives both arguments. The linked\n"
        "source files define these JSON payloads.\n",
    ]
    for role, _, _, _ in CORE_ROLES:
        sections.append(f"### {role.name}\n\n{prompt_block(role.system)}")
    sections.append(
        "Baseline and Conventional Debate prompts are also available in\n"
        "[PROMPTS.md](PROMPTS.md). To change a prompt, edit its Python source and run\n"
        "`python -B scripts/export_prompts.py` to refresh both documents.\n"
    )
    return "\n".join(sections)


def sync_readme(readme: str) -> str:
    """Replace only the marked prompt section, preserving all authored content."""
    if readme.count(README_BEGIN) != 1 or readme.count(README_END) != 1:
        raise ValueError("README.md must contain exactly one generated agent-prompts section")
    prefix, _, remainder = readme.partition(README_BEGIN)
    _, found_end, suffix = remainder.partition(README_END)
    if not found_end:
        raise ValueError("README.md agent-prompts section markers are out of order")
    return prefix + README_BEGIN + "\n" + render_readme_prompts() + "\n" + README_END + suffix


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    root = Path(__file__).resolve().parents[1]
    readme = root/"README.md"
    documents = [(root/"PROMPTS.md", render()),
                 (readme, sync_readme(readme.read_text(encoding="utf-8")))]
    if args.check:
        stale = [path.name for path, content in documents
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        if stale:
            raise SystemExit(f"Runtime prompts differ from {', '.join(stale)}. "
                             "Run python -B scripts/export_prompts.py")
        print("Runtime prompts, README.md and PROMPTS.md agree.")
    else:
        for path, content in documents:
            path.write_text(content, encoding="utf-8")
        print("Updated README.md and PROMPTS.md")

if __name__ == "__main__":
    main()
