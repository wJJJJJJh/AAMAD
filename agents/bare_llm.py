"""Bare LLM baseline: one model pass, no discovery or metadata tools."""
import json
import config
from agents.base import BaseAgent
from state import Prediction
from tools.candidates import normalize_identifier
from tools.evidence import confidence

SYSTEM = """Extract research dataset references from this article and label each
Primary (generated by this study) or Secondary (pre-existing data reused).
Return JSON with mentions: a list of dataset_id, type, evidence and confidence.
Copy identifiers from the article. Do not invent data references."""

class BareLLM(BaseAgent):
    name = "BareLLM"
    system = SYSTEM

def run(article_id: str, fulltext: str, llm=None, trace=None) -> list[Prediction]:
    agent = BareLLM(llm=llm, trace=trace)
    answer = agent._decide(json.dumps({"article_id": article_id,
                           "text": fulltext[:config.MAX_FULLTEXT_CHARS]}, ensure_ascii=False))
    rows = answer.get("mentions", [])
    if not isinstance(rows, list):
        raise ValueError("Bare LLM mentions must be a list")
    predictions = {}
    for row in rows:
        norm = normalize_identifier(row.get("dataset_id", ""))
        label = row.get("type")
        if not norm:
            continue
        if label not in {"Primary", "Secondary"}:
            raise ValueError(f"Bare LLM produced an invalid provenance label for {norm}")
        prediction = Prediction(norm, label, "bare_llm", "bare_llm", confidence(row.get("confidence", 0)))
        old = predictions.get(norm)
        if old is None or prediction.confidence > old.confidence:
            predictions[norm] = prediction
    return list(predictions.values())
